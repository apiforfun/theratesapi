const REGION = new Intl.DisplayNames(['en'], { type: 'region' })
const SPECIAL = { EUR: 'the euro area', XDR: 'International Monetary Fund' }

// "India", "Benin, Burkina Faso, ...", or null when we don't know.
function usedIn (code) {
  if (SPECIAL[code]) return SPECIAL[code]
  const isos = COUNTRIES[code]
  if (!isos) return null
  return isos.map(function (iso) { return REGION.of(iso) }).sort(function (a, b) { return a.localeCompare(b) }).join(', ')
}

module.exports = { COUNTRIES, usedIn }
